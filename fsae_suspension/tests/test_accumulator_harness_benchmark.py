"""Accumulator and harness checks against ngspice, PyBaMM and liionpack (docs/ACCUMULATOR_HARNESS_BENCHMARK_PLAN.md).

The references were generated by scripts/accumulator_harness_reference.py with the tools; the limits are the ones
registered in the plan before the references existed. Re-run the tools with that script; these tests need none of
them installed.
"""
import json
import os
import sys
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
REF = ROOT / "benchmarks" / "electrical" / "accu_harness"

from suspension.ev_electrical_check import pack_along_lap, pack_temperature_along  # noqa: E402
from suspension.harness import WireRun  # noqa: E402


def _ref(name):
    return json.loads((REF / name).read_text(encoding="utf-8"))


def _drop(row):
    w = WireRun(name="w", owner_subsystem="electrics", gauge_awg=row["awg"],
                path_mm=[(0.0, 0.0, 0.0), (row["length_m"] * 1000.0, 0.0, 0.0)], service_loop_mm=0.0, strip_mm=0.0)
    return w.voltage_drop_v(row["current_a"], row["temp_c"])


# ------------------------------------------------------------------------------- H1. ngspice: wire drop ---- #
def test_wire_drop_round1_missed_the_limit_and_is_kept():
    ref = {(r["awg"], r["length_m"], r["temp_c"]): r["drop_v"] for r in _ref("h1_ngspice_wire_drop.json")["rows"]}
    err = {k[0]: 0.0 for k in ref}
    for r in _ref("h1_round1_kinematik.json")["rows"]:
        k = (r["awg"], r["length_m"], r["temp_c"])
        err[k[0]] = max(err[k[0]], abs(r["kinematik_drop_v"] / ref[k] - 1.0) * 100.0)
    #  Round 1: the rounded 22 AWG table entry and the "halves every 3 gauges" rule at 6 AWG missed 0.1 %.
    assert {g for g, e in err.items() if e > 0.1} == {6, 22}
    assert 0.3 < err[6] < 0.4 and 0.1 < err[22] < 0.2


def test_wire_drop_matches_ngspice():
    d = _ref("h1_ngspice_wire_drop.json")
    assert d["tool"].startswith("ngspice") and len(d["rows"]) == 45
    worst = max(abs(_drop(r) / r["drop_v"] - 1.0) for r in d["rows"])
    assert worst <= 0.001                                        # registered: 0.1 %


# ------------------------------------------------------------------------------ A1. PyBaMM: pack on a lap -- #
def test_pack_along_lap_matches_pybamm():
    d = _ref("a1_pybamm_pack_lap.json")
    x = json.loads((ROOT / "benchmarks" / "electrical" / "spice_pack_lap.json").read_text())["inputs"]
    v, i, soc = pack_along_lap(np.array(x["p_terminal_w"]), np.array(x["t_s"]), ocv_soc=x["ocv_soc"],
                               soc0=x["soc0"], capacity_ah=x["capacity_ah"], r_pack_ohm=x["r_pack_ohm"])
    rv, ri, rs = (np.array(d[k]) for k in ("v_terminal_v", "i_a", "soc"))
    assert d["tool"].startswith("PyBaMM") and rv.size == v.size == 520
    n = v.size - 1                         # the last point's voltage and current belong to the last step's power
    assert np.max(np.abs(v[:n] - rv[:n]) / rv[:n]) <= 0.005
    assert np.max(np.abs(i[:n] - ri[:n]) / np.maximum(np.abs(ri[:n]), 1.0)) <= 0.01
    assert abs(soc[-1] - rs[-1]) <= 0.001
    assert min(x["p_terminal_w"]) < 0 < max(x["p_terminal_w"])                       # regen included


# --------------------------------------------------------------------------- A2. PyBaMM: pack temperature -- #
def test_pack_temperature_matches_pybamm():
    d = _ref("a2_pybamm_pack_thermal.json")
    x = d["inputs"]
    cur = np.concatenate([np.full(dur, c) for c, dur in x["blocks_a_s"]] + [[x["blocks_a_s"][-1][0]]])
    t = np.arange(cur.size, dtype=float)
    temp = pack_temperature_along(cur, t, r_pack_ohm=x["r_pack_ohm"], heat_capacity_j_k=x["heat_capacity_j_k"],
                                  temp0_k=x["ambient_k"], cooling_w_k=x["cooling_w_k"], ambient_k=x["ambient_k"])
    ref = np.array(d["temp_k"])
    assert ref.size == temp.size == 1801 and ref.max() - x["ambient_k"] > 20.0     # it actually heats up
    assert np.max(np.abs(temp - ref)) <= 0.2                                        # registered: 0.2 K


# ------------------------------------------------------------------------ A3. liionpack: the pack network -- #
@pytest.mark.parametrize("case, cell_limit, volt_limit", [("ideal", 0.001, 0.001), ("realistic", 0.05, 0.01)])
def test_lumped_pack_matches_the_network(case, cell_limit, volt_limit):
    d = _ref("a3_liionpack_network.json")
    x, c = d["inputs"], d["cases"][case]
    cells = np.array(c["cell_currents_a"])
    even = x["i_pack_a"] / x["n_parallel"]                                   # what the lap check assumes per cell
    lumped = x["n_series"] * x["v_cell_v"] - x["i_pack_a"] * x["n_series"] * x["r_cell_ohm"] / x["n_parallel"]
    assert cells.size == x["n_series"] * x["n_parallel"] == 420
    assert np.max(np.abs(cells - even)) / even <= cell_limit
    assert abs(lumped - c["terminal_v"]) / c["terminal_v"] <= volt_limit


# ---------------------------------------------------- A4. ngspice: the per-cell pack thermal network (add. 1) -- #
def test_pack_thermal_network_matches_ngspice():
    from suspension.pack_thermal import AirflowParams, CellParams, Fan, PackLayout, PackThermalModel
    d = _ref("a4_ngspice_pack_network.json")
    x = d["inputs"]
    cell = CellParams(mass_kg=x["cell_mass_kg"], cp=x["cell_cp_j_kgk"], r_internal_ohm=x["r_cell_ohm"],
                      r_tempco_per_c=0.0, surface_area_m2=x["surface_m2"], pitch_mm=x["pitch_mm"])
    lay = PackLayout(rows=x["rows"], cols=x["cols"], parallel=x["parallel"], cell=cell, ambient_c=x["ambient_c"])
    fans = [Fan(**f) for f in x["fans"]]
    air = AirflowParams(mode="proxy", enable_wake_warming=False, h_floor=8.0)     # the still-air value when A4 was recorded
    assert np.allclose(air.h_field(lay.positions_mm(), fans), x["h_w_m2k"], rtol=0, atol=1e-9)   # same inputs
    res = PackThermalModel(layout=lay, fans=fans, airflow=air, k_cell_cell=x["k_cell_cell_w_k"]).simulate(
        np.array(d["t_s"]), np.array(x["pack_current_a"]))
    ref = np.array(d["temp_c"])
    assert res.ok and res.temp_history_c.shape == ref.shape == (1201, 24)
    assert np.ptp(ref[-1]) > 1.0                                      # the fans make the cells differ
    assert np.max(np.abs(res.temp_history_c - ref)) <= 0.2           # registered: 0.2 K


# --------------------------------------------------- B1/B2. ht tube-bank correlations: airflow (addendum 2) -- #
def _bank():
    from suspension.pack_thermal import CellParams, PackLayout
    d = _ref("b1_ht_tube_bank.json")
    x = d["inputs"]
    lay = PackLayout(rows=x["cells_across"], cols=x["rows_along_flow"], cell=CellParams(pitch_mm=x["pitch_m"] * 1000))
    return d, x, lay


def _corr(flow):
    rows = flow["h_row_w_m2k"]
    return np.array([rows[k] for k in ("zukauskas_bejan", "grimison", "esdu_73031")])


def test_airflow_proxy_misses_the_tube_bank_correlations():
    from suspension.pack_thermal import AirflowParams, Fan
    d, x, lay = _bank()
    mean_h = {}
    worst = 0.0
    for cfm, flow in d["flows"].items():
        fan = Fan(x_mm=0.0, y_mm=x["cells_across"] * x["pitch_m"] * 500.0, cfm=float(cfm))
        h = AirflowParams(mode="proxy").h_field(lay.positions_mm(), [fan]).reshape(x["cells_across"], x["rows_along_flow"])
        ref = _corr(flow).mean(axis=0)
        worst = max(worst, float(np.max(np.abs(h / ref - 1.0))))
        mean_h[cfm] = (h.mean(), ref.mean())
        assert h[:, 0].mean() > h[:, -1].mean() and ref[0] < ref[-1]       # it cools the wrong end
    assert worst > 0.9                                                      # registered 30 %: a miss, kept
    proxy_ratio, ref_ratio = mean_h["80"][0] / mean_h["20"][0], mean_h["80"][1] / mean_h["20"][1]
    assert abs(proxy_ratio / ref_ratio - 1.0) <= 0.15   # registered 15 %: the flow scaling passes (10 %)


def test_duct_mode_round1_missed_the_implementation_limit_and_is_kept():
    d, _, _ = _bank()
    r1 = _ref("b2_round1_kinematik.json")["h_row_w_m2k"]
    dev = max(np.max(np.abs(np.array(r1[c]) / np.array(f["h_row_w_m2k"]["zukauskas_bejan"]) - 1.0))
              for c, f in d["flows"].items())
    assert 0.04 < dev < 0.05                                                # 4.35 %: Incropera's coarse row table


def test_duct_mode_matches_the_tube_bank_correlations():
    from suspension.pack_thermal import AirflowParams
    d, x, lay = _bank()
    for cfm, flow in d["flows"].items():
        h = AirflowParams(mode="duct", duct_cfm=float(cfm)).h_field(lay.positions_mm(), [])
        h = h.reshape(x["cells_across"], x["rows_along_flow"])
        corr = _corr(flow)
        assert np.max(np.abs(h / corr[0] - 1.0)) <= 0.02                    # registered: 2 % against ht's Zukauskas
        assert np.max(np.abs(h / corr.mean(axis=0) - 1.0)) <= 0.30          # B1's 30 % against all three
        assert np.all(h >= corr.min(axis=0) * 0.999) and np.all(h <= corr.max(axis=0) * 1.001)


# ---------------------------------------------------------- C1. ht: still-air natural convection (add. 3) -- #
def _still_air_err(h):
    rows = _ref("c1_ht_still_air.json")["rows"]
    return max(abs(h / r[k] - 1.0) for r in rows for k in ("h_horizontal_w_m2k", "h_vertical_w_m2k"))


def test_still_air_round1_was_optimistic_and_is_kept():
    assert 0.7 < _still_air_err(8.0) < 0.8                    # the old 8 W/m²K: up to 78 % more cooling than air gives


def test_still_air_cooling_matches_natural_convection():
    from suspension.pack_thermal import AirflowParams
    assert AirflowParams().h_floor == 5.5
    assert _still_air_err(AirflowParams().h_floor) <= 0.30    # registered: 30 % of both, 5 to 40 K rise


