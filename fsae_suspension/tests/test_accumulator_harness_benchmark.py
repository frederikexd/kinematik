"""Accumulator and harness checks against ngspice, PyBaMM and liionpack (docs/ACCUMULATOR_HARNESS_BENCHMARK_PLAN.md).

The references were generated by scripts/accumulator_harness_reference.py with the tools; the limits are the ones
registered in the plan before the references existed. Re-run the tools with that script; these tests need none of
them installed.
"""
import json
import os
import sys
from pathlib import Path

import numpy as np
import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
REF = ROOT / "benchmarks" / "electrical" / "accu_harness"

from suspension.ev_electrical_check import pack_along_lap, pack_temperature_along  # noqa: E402
from suspension.harness import WireRun  # noqa: E402


def _ref(name):
    return json.loads((REF / name).read_text(encoding="utf-8"))


def _drop(row):
    w = WireRun(name="w", owner_subsystem="electrics", gauge_awg=row["awg"],
                path_mm=[(0.0, 0.0, 0.0), (row["length_m"] * 1000.0, 0.0, 0.0)], service_loop_mm=0.0, strip_mm=0.0)
    return w.voltage_drop_v(row["current_a"], row["temp_c"])


# ------------------------------------------------------------------------------- H1. ngspice: wire drop ---- #
def test_wire_drop_round1_missed_the_limit_and_is_kept():
    ref = {(r["awg"], r["length_m"], r["temp_c"]): r["drop_v"] for r in _ref("h1_ngspice_wire_drop.json")["rows"]}
    err = {k[0]: 0.0 for k in ref}
    for r in _ref("h1_round1_kinematik.json")["rows"]:
        k = (r["awg"], r["length_m"], r["temp_c"])
        err[k[0]] = max(err[k[0]], abs(r["kinematik_drop_v"] / ref[k] - 1.0) * 100.0)
    #  Round 1: the rounded 22 AWG table entry and the "halves every 3 gauges" rule at 6 AWG missed 0.1 %.
    assert {g for g, e in err.items() if e > 0.1} == {6, 22}
    assert 0.3 < err[6] < 0.4 and 0.1 < err[22] < 0.2


def test_wire_drop_matches_ngspice():
    d = _ref("h1_ngspice_wire_drop.json")
    assert d["tool"].startswith("ngspice") and len(d["rows"]) == 45
    worst = max(abs(_drop(r) / r["drop_v"] - 1.0) for r in d["rows"])
    assert worst <= 0.001                                        # registered: 0.1 %


# ------------------------------------------------------------------------------ A1. PyBaMM: pack on a lap -- #
def test_pack_along_lap_matches_pybamm():
    d = _ref("a1_pybamm_pack_lap.json")
    x = json.loads((ROOT / "benchmarks" / "electrical" / "spice_pack_lap.json").read_text())["inputs"]
    v, i, soc = pack_along_lap(np.array(x["p_terminal_w"]), np.array(x["t_s"]), ocv_soc=x["ocv_soc"],
                               soc0=x["soc0"], capacity_ah=x["capacity_ah"], r_pack_ohm=x["r_pack_ohm"])
    rv, ri, rs = (np.array(d[k]) for k in ("v_terminal_v", "i_a", "soc"))
    assert d["tool"].startswith("PyBaMM") and rv.size == v.size == 520
    n = v.size - 1                         # the last point's voltage and current belong to the last step's power
    assert np.max(np.abs(v[:n] - rv[:n]) / rv[:n]) <= 0.005
    assert np.max(np.abs(i[:n] - ri[:n]) / np.maximum(np.abs(ri[:n]), 1.0)) <= 0.01
    assert abs(soc[-1] - rs[-1]) <= 0.001
    assert min(x["p_terminal_w"]) < 0 < max(x["p_terminal_w"])                       # regen included


# --------------------------------------------------------------------------- A2. PyBaMM: pack temperature -- #
def test_pack_temperature_matches_pybamm():
    d = _ref("a2_pybamm_pack_thermal.json")
    x = d["inputs"]
    cur = np.concatenate([np.full(dur, c) for c, dur in x["blocks_a_s"]] + [[x["blocks_a_s"][-1][0]]])
    t = np.arange(cur.size, dtype=float)
    temp = pack_temperature_along(cur, t, r_pack_ohm=x["r_pack_ohm"], heat_capacity_j_k=x["heat_capacity_j_k"],
                                  temp0_k=x["ambient_k"], cooling_w_k=x["cooling_w_k"], ambient_k=x["ambient_k"])
    ref = np.array(d["temp_k"])
    assert ref.size == temp.size == 1801 and ref.max() - x["ambient_k"] > 20.0     # it actually heats up
    assert np.max(np.abs(temp - ref)) <= 0.2                                        # registered: 0.2 K


# ------------------------------------------------------------------------ A3. liionpack: the pack network -- #
@pytest.mark.parametrize("case, cell_limit, volt_limit", [("ideal", 0.001, 0.001), ("realistic", 0.05, 0.01)])
def test_lumped_pack_matches_the_network(case, cell_limit, volt_limit):
    d = _ref("a3_liionpack_network.json")
    x, c = d["inputs"], d["cases"][case]
    cells = np.array(c["cell_currents_a"])
    even = x["i_pack_a"] / x["n_parallel"]                                   # what the lap check assumes per cell
    lumped = x["n_series"] * x["v_cell_v"] - x["i_pack_a"] * x["n_series"] * x["r_cell_ohm"] / x["n_parallel"]
    assert cells.size == x["n_series"] * x["n_parallel"] == 420
    assert np.max(np.abs(cells - even)) / even <= cell_limit
    assert abs(lumped - c["terminal_v"]) / c["terminal_v"] <= volt_limit


