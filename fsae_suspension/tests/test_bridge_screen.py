"""The solder-bridge gap screen against KiCad 7's own pad geometry (docs/ELECTRICAL_BENCHMARK_PLAN.md, addendum 16).
The reference was generated by scripts/bridge_gap_reference.py with pcbnew; these tests need only the demo boards."""
import json
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from suspension import pcb_doctor as D  # noqa: E402

DEMOS = Path("/usr/share/kicad/demos")
needs_demos = pytest.mark.skipif(not DEMOS.is_dir(), reason="KiCad demo boards not installed")
REF = json.loads((ROOT / "benchmarks" / "electrical" / "bridge_gaps" / "kicad7_pad_gaps.json").read_text("utf-8"))
PATHS = {Path(p).stem: p for p in json.loads(
    (ROOT / "benchmarks" / "electrical" / "kicad_boards.json").read_text("utf-8"))["boards"]}


def _kicad(name):
    out = {}
    for r in REF["boards"][name]:
        k = tuple(r["pins"])
        out[k] = min(out.get(k, 9.0), r["gap_mm"])
    return out


def test_reference_is_kicad_on_every_demo_board():
    assert REF["tool"].startswith("KiCad 7") and set(REF["boards"]) == set(PATHS) and len(PATHS) == 14


@needs_demos
@pytest.mark.parametrize("name", sorted(PATHS))
def test_gap_screen_matches_kicad(name):
    p = PATHS[name]
    mine = {tuple(sorted(r["pins"])): r["gap_mm"] for r in D.bridge_risk_pairs(D.parse_board((DEMOS / p).read_bytes(), p))}
    ref = _kicad(name)
    assert not [k for k, g in ref.items() if g < 0.34 and k not in mine]                     # none missed
    assert not [k for k in mine if ref.get(k, 9.0) > 0.36]                                    # none extra
    assert all(abs(g - ref[k]) <= 0.01 for k, g in mine.items())                             # registered 0.01 mm


def test_round1_missed_custom_pads_and_is_kept():
    #  Round 1 built only each pad's anchor, so the custom-shaped solder-jumper pads JP1 on StickHub (0.15 mm)
    #  and pic_programmer (0.25 mm) were missed. Custom pad copper is now included.
    assert _kicad("StickHub")[("JP1.1", "JP1.2")] == pytest.approx(0.15, abs=1e-3)
    assert _kicad("pic_programmer")[("JP1.1", "JP1.2")] == pytest.approx(0.2496, abs=1e-3)


def _board(pads):
    b = D.PcbBoard(nets={i + 1: n for i, n in enumerate(sorted({p[1] for p in pads}))})
    ids = {n: i for i, n in b.nets.items()}
    fp = D.PcbFootprint(ref="U1", value="x", layer="F.Cu", at=(0.0, 0.0))
    for num, net, x, y, w, h, kw in pads:
        fp.pads.append(D.PcbPad(number=num, net=ids[net] if net else 0, net_name=net, at=(x, y), size=(w, h), **kw))
    b.footprints.append(fp)
    return b


def test_known_gaps_and_order():
    b = _board([("1", "GND", 0.0, 0.0, 1.0, 0.3, {"shape": "rect"}),
                ("2", "+5V", 0.0, 0.5, 1.0, 0.3, {"shape": "rect"}),            # 0.2 mm from pin 1
                ("3", "SDA", 0.0, 1.0, 1.0, 0.3, {"shape": "rect"}),            # 0.2 mm from pin 2
                ("4", "SCL", 0.0, 1.45, 1.0, 0.3, {"shape": "rect"}),           # 0.15 mm from pin 3
                ("5", "+3V3", 3.0, 0.0, 0.6, 0.6, {"shape": "circle"}),
                ("6", "+5V", 3.9, 0.0, 0.6, 0.6, {"shape": "circle"}),          # 0.3 mm between two supplies
                ("7", "GND", 6.0, 0.0, 1.0, 1.0, {"shape": "rect"}),
                ("8", "", 6.0, 1.1, 1.0, 1.0, {"shape": "rect"}),               # unconnected: skipped
                ("9", "SDA", 8.0, 0.0, 1.0, 1.0, {"shape": "rect"}),
                ("10", "SCL", 8.0, 1.5, 1.0, 1.0, {"shape": "rect"})])          # 0.5 mm: past the screen
    rows = D.bridge_risk_pairs(b)
    assert [(r["pins"], r["kind"]) for r in rows] == [
        (("U1.1", "U1.2"), "supply to ground"), (("U1.5", "U1.6"), "two supplies"),
        (("U1.2", "U1.3"), "supply to signal"), (("U1.3", "U1.4"), "two signals")]
    assert [round(r["gap_mm"], 6) for r in rows] == [0.2, 0.3, 0.2, 0.15]
    assert all(r["side"] == "F.Cu" for r in rows)


def test_sides_rotation_and_shapes():
    top = dict(shape="rect", layer="F.Cu")
    bot = dict(shape="rect", layer="B.Cu")
    b = _board([("1", "GND", 0.0, 0.0, 1.0, 0.3, top), ("2", "+5V", 0.0, 0.5, 1.0, 0.3, bot)])
    assert D.bridge_risk_pairs(b) == []                                         # opposite sides never bridge
    b = _board([("1", "GND", 0.0, 0.0, 1.0, 0.3, top), ("2", "+5V", 0.0, 0.5, 1.0, 1.0, dict(shape="rect", through=True))])
    assert D.bridge_risk_pairs(b)[0]["side"] == "F.Cu"                          # a through-hole pad is on both
    b = _board([("1", "GND", 0.0, 0.0, 1.0, 0.3, dict(shape="rect", angle_deg=90.0)),
                ("2", "+5V", 0.4, 0.0, 1.0, 0.3, dict(shape="rect", angle_deg=90.0))])
    assert D.bridge_risk_pairs(b)[0]["gap_mm"] == pytest.approx(0.1, abs=1e-9)  # turned 90 degrees
    b = _board([("1", "GND", 0.0, 0.0, 1.2, 0.6, dict(shape="oval")), ("2", "+5V", 0.0, 0.8, 1.2, 0.6, dict(shape="oval"))])
    assert D.bridge_risk_pairs(b)[0]["gap_mm"] == pytest.approx(0.2, abs=1e-3)
    b = _board([("1", "GND", 0.0, 0.0, 1.0, 1.0, dict(shape="rect")), ("2", "+5V", 0.0, 0.0, 0.2, 0.2, dict(shape="rect"))])
    assert D.bridge_risk_pairs(b)[0]["gap_mm"] == 0.0                           # overlapping copper


def test_net_classes():
    assert [D._net_class(n) for n in ("GND", "/power/AGND", "VSS", "+5V", "3V3", "VBAT", "12V", "SDA", "Net-(R1-Pad1)")] \
        == ["ground", "ground", "ground", "supply", "supply", "supply", "supply", "signal", "signal"]


def test_report_sections():
    b = _board([("1", "GND", 0.0, 0.0, 1.0, 0.3, {"shape": "rect"}), ("2", "+5V", 0.0, 0.5, 1.0, 0.3, {"shape": "rect"})])
    md = "\n".join(D.bridge_check_md(b))
    assert "1 pin pairs" in md and "| 1 | U1.1 – U1.2 | `GND` – `+5V` | 0.20 mm | supply to ground | F.Cu |" in md
    assert "No pads on different nets" in "\n".join(D.bridge_check_md(_board([("1", "GND", 0.0, 0.0, 1.0, 1.0, {})])))
    sheet = D.bringup_sheet_md(b)
    assert sheet.startswith("# Bring-up sheet") and "Solder-bridge check" in sheet
    many = [(str(i), "GND" if i % 2 else "+5V", 0.0, 0.5 * i, 1.0, 0.3, {"shape": "rect"}) for i in range(50)]
    assert "more, all lower priority or wider" in "\n".join(D.bridge_check_md(_board(many), limit=10))


# ------------------------------------------------- addendum 17: native Altium boards via KiCad's importer -- #
ALT = json.loads((ROOT / "benchmarks" / "electrical" / "bridge_gaps" / "kicad7_altium_pad_gaps.json").read_text("utf-8"))


@pytest.mark.parametrize("name", sorted(ALT["boards"]))
def test_altium_gap_screen_matches_kicads_importer(name):
    ref = {}
    for r in ALT["boards"][name]:
        ref[tuple(r["pins"])] = min(ref.get(tuple(r["pins"]), 9.0), r["gap_mm"])
    mine = {tuple(r["pins"]): r["gap_mm"] for r in ALT["kinematik"][name]}
    assert not [k for k, g in ref.items() if g < 0.34 and k not in mine]
    assert not [k for k in mine if ref.get(k, 9.0) > 0.36]
    assert all(abs(g - ref[k]) <= 0.01 for k, g in mine.items())


def test_altium_reference_covers_the_six_native_boards():
    assert len(ALT["boards"]) == 6 and sum(len(v) for v in ALT["kinematik"].values()) == 168


def test_altium_recorded_pairs_are_what_the_reader_gives_now():
    """Set KK_ALTIUM_KIT to the kit folder (<board>.PcbDoc) to re-read the boards here."""
    import os
    kit = os.environ.get("KK_ALTIUM_KIT")
    if not kit:
        pytest.skip("KK_ALTIUM_KIT not set")
    for name, rows in ALT["kinematik"].items():
        p = Path(kit) / f"{name}.PcbDoc"
        got = [list(r["pins"]) for r in D.bridge_risk_pairs(D.parse_board(p.read_bytes(), p.name))]
        assert got == [r["pins"] for r in rows], name


